"""Prepare the synthetic academic-demo bundle with the *released* CLI.

Run with the interpreter where the exported v1.2.0 is installed. No inputs in
the repository are edited. All generated bytes stay in ignored web/data/.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import shutil
import subprocess
import sys

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
RELEASE = "45237d7caaea2aa4b81359e46f1623918645078c"
ARTIFACTS = ("report.json", "report.md", "relationship-regressions.geojson")


def write_json(path, obj):
    path.write_text(json.dumps(obj, ensure_ascii=False, indent=2) + "\n", encoding="utf-8", newline="\n")


def identity(path):
    raw = path.read_bytes()
    return {"sha256": hashlib.sha256(raw).hexdigest(), "size_bytes": len(raw)}


def require(ok, message):
    if not ok:
        raise ValueError(message)


def copy_case(key, source, output, files, metadata, expected_exit):
    dest = HERE / "web/data" / key
    dest.mkdir(parents=True, exist_ok=True)
    config = source / files["config"]
    run = subprocess.run([sys.executable, "-m", "geoimpact.cli", "analyze", "--config", str(config), "--out", str(output)],
                         cwd=REPO, capture_output=True, text=True)
    require(run.returncode == expected_exit, f"{key}: unexpected CLI exit {run.returncode}")
    # Load the exact emitted report. Do not reconstruct, round or reserialize it.
    report = json.loads((output / "report.json").read_bytes())
    require(report["report_version"] == "5" and report["provenance"]["engine"]["geoimpact_ci"] == "1.2.0", "Released V5 required")
    entries = {}
    flat = {k: v for k, v in files.items() if k != "dependencies"}
    flat.update({f"dependency-{i}": d["file"] for i, d in enumerate(files["dependencies"])})
    for role, name in flat.items():
        target = dest / name
        shutil.copyfile(source / name, target)
        entries[role] = {"path": f"data/{key}/{name}", **identity(target)}
    for name in ARTIFACTS:
        shutil.copyfile(output / name, dest / name)
        entries[name] = {"path": f"data/{key}/{name}", **identity(dest / name)}
    manifest = {"bundle_version": 1, "id": key, "kind": "completed", "release_commit": RELEASE,
                "display_crs": "OGC:CRS84", "files": entries, "dependencies": files["dependencies"], **metadata}
    write_json(dest / "manifest.json", manifest)
    return {"id": key, "title": metadata["title"], "path": f"data/{key}/manifest.json", **identity(dest / "manifest.json")}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--engine", type=Path, required=True, help="directory exported from the exact v1.2.0 tag")
    args = parser.parse_args()
    engine = args.engine.resolve()
    # The module imported by the subprocess must be precisely the released source.
    import geoimpact.cli
    require(Path(geoimpact.cli.__file__).resolve().is_relative_to(engine), "Use an interpreter with the exported release installed")
    tree = subprocess.check_output(["git", "ls-tree", "-r", RELEASE, "src/geoimpact", "tests/fixtures"], cwd=REPO, text=True)
    for line in tree.splitlines():
        prefix, name = line.split("\t")
        expected = subprocess.check_output(["git", "cat-file", "blob", prefix.split()[2]], cwd=REPO)
        require((engine / name).read_bytes() == expected, f"Engine differs from release: {name}")
    web = HERE / "web"
    data = web / "data"
    if data.exists():
        shutil.rmtree(data)
    data.mkdir(parents=True)
    work = REPO / "work/studio-outputs"
    work.mkdir(parents=True, exist_ok=True)
    fixtures = engine / "tests/fixtures"
    files = {"config": "geoimpact.yml", "base": "districts_base.geojson", "candidate": "districts_candidate.geojson",
             "dependencies": [{"dataset": "hotels", "file": "hotels.geojson"}, {"dataset": "tourism_pois", "file": "tourism_pois.geojson"}]}
    source = "https://github.com/soroushkarahrodi79-oss/geoimpact-ci/blob/" + RELEASE + "/docs/GATE_1_REPORT.md"
    metadata = {"title": {"es": "Límites sintéticos · BLOCK", "en": "Synthetic boundaries · BLOCK"}, "category": "synthetic",
                "editions": ["BASE · fixture", "CANDIDATE · fixture"], "inventory_date": "Fixture sintético / synthetic fixture",
                "attribution": "GeoImpact CI contributors · MIT · synthetic fixtures, not official administrative data",
                "sources": [{"title": "Gate 1 · construction and limitations", "url": source, "terms": "MIT; controlled synthetic rectangles"}],
                "limitations": {"es": "Geometrías artificiales de Gate 1; los nombres conservan los IDs originales. No son secciones INE ni límites administrativos oficiales. PASS/BLOCK describe la política configurada, no daños ni corrección de los datos.",
                                "en": "Artificial Gate 1 geometry; labels retain original IDs. These are not INE sections or official boundaries. PASS/BLOCK describes configured policy, not harm or data correctness."}}
    cases = [copy_case("synthetic-block", fixtures, work / "synthetic-block", files, metadata, 1)]
    # Qualify against the unchanged release verifier, without importing it as an adapter.
    expected = {"report.json": "d09f70d2f7fa07cef3fa87f5b1fe73d932c8f9c4619487c4a0fe8c4cc1d7b8dd",
                "report.md": "65ca9d67dd7ff59bc148fccc003354ea3201f51707f3e73ca2fd96dac208d95a",
                "relationship-regressions.geojson": "a3557416a5a6f7c6eb5c3fa5d4b14a48864249f208981138e6d21bc542318978"}
    require(all(identity(work / "synthetic-block" / n)["sha256"] == h for n, h in expected.items()), "Frozen synthetic hash mismatch")
    files = {**files, "config": "geoimpact-pass.yml"}
    metadata = {**metadata, "title": {"es": "Mismos límites · PASS", "en": "Same boundaries · PASS"}}
    cases.append(copy_case("synthetic-pass", fixtures, work / "synthetic-pass", files, metadata, 0))
    missing = work / "intentionally-missing.yml"
    require(not missing.exists(), "ERROR scenario requires a missing config")
    run = subprocess.run([sys.executable, "-m", "geoimpact.cli", "analyze", "--config", str(missing), "--out", str(work / "analysis-error")],
                         capture_output=True, text=True, cwd=REPO)
    require(run.returncode == 2 and "Verdict:" not in run.stdout, "ERROR contract failed")
    message = run.stderr.strip().replace(str(missing), "[intentionally-missing.yml]")
    error = {"bundle_version": 1, "id": "synthetic-error", "kind": "analysis-error", "exit_code": run.returncode,
             "stderr": message, "stderr_redaction": "Absolute config path replaced with a filename placeholder",
             "title": {"es": "Error de análisis · sin informe", "en": "Analysis error · no report"}}
    dest = web / "data/synthetic-error"; dest.mkdir(exist_ok=True)
    write_json(dest / "manifest.json", error)
    cases.append({"id": error["id"], "title": error["title"], "path": "data/synthetic-error/manifest.json", **identity(dest / "manifest.json")})
    catalog = {"studio_version": "0.1.0-academic-demo", "R1": "OPEN", "full_viewer": "HOLD", "cases": cases}
    write_json(web / "catalog.json", catalog)
    (web / "trust.js").write_text('export const catalogHash = "' + identity(web / "catalog.json")["sha256"] + '";\n', encoding="utf-8", newline="\n")
    print(f"Prepared {len(cases)} allowlisted synthetic academic-demo cases. R1 OPEN / full viewer HOLD.")


if __name__ == "__main__":
    main()
